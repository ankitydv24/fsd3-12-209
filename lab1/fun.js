// write a function to take any digit (0-9) and return its in words as like 0-one, 5- five
const toWords = (digit)=>
{
    const words =["Zero","One","Two","Three","Four","Five","Six","Seven","Eight","Nine"];
    return words[digit];
}
console.log(toWords(5));

